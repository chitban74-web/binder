// Extracts the client<->server message protocol from the game bundle.
// usage: node proto.js <main.js> <out.json>
const fs = require('fs'), acorn = require('acorn'), walk = require('acorn-walk');
const [, , src, out] = process.argv;
const code = fs.readFileSync(src, 'utf8');
const ast = acorn.parse(code, { ecmaVersion: 'latest', sourceType: 'module' });
const snip = (n, max = 160) => { const s = code.slice(n.start, n.end); return s.length > max ? s.slice(0, max) + '…' : s; };

// client -> server: <x>.send({type:"...", ...})
const send = {};
walk.simple(ast, {
  CallExpression(n) {
    const c = n.callee;
    if (c.type !== 'MemberExpression' || c.property.name !== 'send') return;
    const a = n.arguments[0];
    if (!a || a.type !== 'ObjectExpression') return;
    const tp = a.properties.find(p => p.type === 'Property' && p.key.name === 'type' && p.value.type === 'Literal');
    if (!tp) return;
    const t = tp.value.value;
    const e = send[t] = send[t] || { fields: {}, examples: [] };
    for (const p of a.properties) {
      if (p.type !== 'Property') { e.fields['...spread'] = snip(p, 80); continue; }
      const k = p.key.name ?? p.key.value; if (k === 'type') continue;
      (e.fields[k] = e.fields[k] || new Set()).add(snip(p.value, 80));
    }
    if (e.examples.length < 3) e.examples.push(snip(n, 260));
  }
});
for (const e of Object.values(send)) for (const k in e.fields) if (e.fields[k] instanceof Set) e.fields[k] = [...e.fields[k]].slice(0, 4);

// server -> client: the big `switch(msg.type)` dispatcher (largest switch on `<id>.type`);
// for each case, collect the `<msg>.<field>` reads inside it.
let disp = null;
walk.simple(ast, {
  SwitchStatement(n) {
    const d = n.discriminant;
    if (d.type === 'MemberExpression' && d.object.type === 'Identifier' && d.property.name === 'type' && (!disp || n.cases.length > disp.cases.length)) disp = n;
  }
});
const recv = {};
if (disp) {
  const msg = disp.discriminant.object.name;
  let pending = [];
  for (const c of disp.cases) {
    if (c.test && c.test.type === 'Literal') pending.push(c.test.value);
    if (!c.consequent.length) continue; // fall-through: share the next body
    const fields = new Set();
    for (const st of c.consequent) walk.simple(st, {
      MemberExpression(m) { if (m.object.type === 'Identifier' && m.object.name === msg && !m.computed) fields.add(m.property.name); }
    });
    fields.delete('type');
    for (const t of pending) recv[t] = { fields: [...fields].sort(), body: snip(c, 300) };
    pending = [];
  }
}

// rooms / endpoints
const endpoints = [...new Set(code.match(/\/api\/[A-Za-z0-9_\/-]+/g))].sort();
const rooms = [...new Set((code.match(/joinOrCreate\([^,]{0,80}/g) || []))];

fs.mkdirSync(require('path').dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify({ send, recv, endpoints, rooms }, null, 1));
const esc = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const md = ['# Message reference (generated by tools/proto.js)', '',
  `## client → server: room.send("input", {type, ...}) — ${Object.keys(send).length} types`, '', '| type | fields (example expressions from the client) |', '|---|---|',
  ...Object.keys(send).sort().map(t => `| \`${t}\` | ${esc(Object.entries(send[t].fields).map(([k, v]) => `${k}: ${Array.isArray(v) ? v.slice(0, 2).join(' / ') : v}`).join('; ') || '—')} |`), '',
  `## server → client: room.onMessage("server", msg | msg[]) — ${Object.keys(recv).length} types`, '', '| type | fields read by the client |', '|---|---|',
  ...Object.keys(recv).sort().map(t => `| \`${t}\` | ${esc(recv[t].fields.join(', ') || '—')} |`), '',
  '## HTTP endpoints', '', ...endpoints.map(e => `- \`${e}\``), ''];
fs.writeFileSync(out.replace(/\.json$/, '.md'), md.join('\n'));
console.log('send types', Object.keys(send).length, 'recv candidates', Object.keys(recv).length, 'endpoints', endpoints.length);
