// tools/build_item_names.js — item id -> Thai name for the web manager's market tab (manager/public/item_names.js).
// The market sends raw item ids (e.g. "scythe_t9|rare..."); names come from the game's item table in the data dump.
// Run after a data dump of a new game build:  node tools/build_item_names.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const src = path.join(ROOT, 'data', 'items', 'items_all.json');
const out = path.join(ROOT, 'manager', 'public', 'item_names.js');
const j = JSON.parse(fs.readFileSync(src, 'utf8'));
const list = Array.isArray(j) ? j : Object.entries(j).map(([id, v]) => ({ id, ...v }));
const names = {};
for (const it of list) if (it && it.id && it.name) names[it.id] = it.name;
fs.writeFileSync(out, '// generated by tools/build_item_names.js — do not edit\nwindow.BT_ITEM_NAMES = ' + JSON.stringify(names) + ';\n');
console.log(`${Object.keys(names).length} names -> ${path.relative(ROOT, out)}`);
